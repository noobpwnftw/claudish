"""Write claudish/web/lab-states.js: the panel of every design-lab state, made by driving a real
Composition into it, so the lab (claudish/web/design.js) and the native previews draw what the
input method draws, not a hand copy (docs/design/design.md).

  python scripts/lab_states.py           # write the file
  python scripts/lab_states.py --check   # exit 1 if it is out of date (the unit tests run this)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from claudish.composition import Composition  # noqa: E402

OUT = ROOT / "claudish/web/lab-states.js"
PREFIX = "// Generated by scripts/lab_states.py from claudish/composition.py: do not edit.\nwindow.LAB_STATES = "
DRAFTS = ["Thank you for the invitation — I'm afraid I can't make the offsite this time.",
          "I'd love to join, but I won't be able to attend the offsite.",
          "Unfortunately the offsite clashes with a deadline, so I'll have to sit this one out."]
ANSWER = ("The parser reached the end of the file while a string was still open. The quote on line 12 is never "
          "closed, so everything after it was read as part of the string.")


def composing(text):
    state = Composition()
    state.mode = "compose"
    state.change(text)
    return state


def sent(text):
    state = composing(text)
    state.submit()
    return state


def asked(text, question):
    state = sent(text)
    state.ask(state.revision, question, "s")
    return state


def states():
    """(lab state id, panel description) for every state the lab draws."""
    yield "compose", composing("running late, start without me").panel()
    state = composing("running late, start without me")
    state.tab()
    yield "rewriting", state.panel()
    state.offer(state.revision, "I'm running a little late — please start without me.")
    yield "converted", state.panel()
    state = sent("decline the offsite politely")
    yield "sent", state.panel()
    state.offer(state.revision, DRAFTS[0], DRAFTS[1:])
    yield "drafts", state.panel()
    state.enter()  # Enter on a draft: its Tab lights
    yield "nudged", state.panel()
    state = sent("decline the offsite politely")
    state.offer(state.revision, DRAFTS[0], DRAFTS[1:], hosted="Claude")
    yield "hosted", state.panel()
    question = {"id": "q", "label": "The model asks", "body": "The whole thread, or only the last reply?",
                "choices": [{"label": "The whole thread"}, {"label": "Only the last reply"}]}
    state = asked("summarize this thread", question)
    yield "ask", state.panel()
    for char in "only the last two days":
        state.insert(char)
    yield "reply", state.panel()
    state.answer_text()
    yield "answered", state.panel()
    state = asked("push my branch", {"id": "p", "permission": True, "label": "Claude Code wants to run",
                                     "body": "git push origin parser-fix", "code": True,
                                     "choices": [{"label": "Deny"}, {"label": "Allow"}]})
    yield "permission", state.panel()
    state = asked("have claude fix the failing parser test", {
        "id": "h", "permission": True, "label": "Hand off to Claude Code", "body": "Fix the failing parser test",
        "choices": [{"label": "No", "legend": "answer it here"}, {"label": "Yes", "legend": "it opens in a new window"}]})
    yield "handoff", state.panel()
    state = asked("what does this error mean", {"id": "r", "read": True, "label": "The model says", "body": ANSWER,
                                                "choices": [{"label": "Insert it"}, {"label": "Dismiss"}]})
    yield "answer", state.panel()
    state = sent("fix the failing parser test")
    state.note(state.revision, "Reading tests/test_parser.py")
    yield "progress", state.panel()
    state = sent("decline the offsite politely")
    state.fail(state.revision, "Connection refused")
    yield "failed", state.panel()
    state = sent("undo my last commit but keep the changes")
    state.offer(state.revision, "git reset --soft HEAD~1", ["git reset --mixed HEAD~1"])
    yield "terminal", state.panel()
    yield "dropped", Composition().dropped_toast()
    state = sent("decline the offsite politely")
    state.offer(state.revision, DRAFTS[0], DRAFTS[1:])
    state.leave("app")
    yield "returned", state.returned("app")
    state = Composition()
    state.mode = "compose"
    yield "mode-compose", state.toast()
    state.mode = "continue"
    yield "mode-continue", state.toast()


def render():
    return PREFIX + json.dumps({name: panel for name, panel in states()}, ensure_ascii=False, indent=1) + ";\n"


def load(path=OUT):
    """The states as written: {state id: panel description} (for the native previews)."""
    text = Path(path).read_text(encoding="utf-8")
    return json.loads(text[len(PREFIX):].rstrip().rstrip(";"))


def main():
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("claudish/web/lab-states.js is out of date: run python scripts/lab_states.py")
            return 1
        return 0
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
